# read genotype table (wide format, 2 cols per SNP)
geno <- read.table("SNPs/DATA/Puma_SNP_genotypes.tab",
                   header = TRUE,
                   sep = "\t",
                   stringsAsFactors = FALSE,
                   check.names = FALSE)

# remove metadata columns (ID, lat, lon, dataset)
gt <- geno[, -(1:4)]
nloci <- ncol(gt) / 2  # number of diploid loci

# create empty matrix for 0/1/2 genotype dosage
dosage <- matrix(NA, nrow = nrow(gt), ncol = nloci)

# convert allele pairs to dosage (0,1,2 copies of alt allele)
for(i in 1:nloci){
  a1 <- gt[, 2*i - 1]  # allele 1
  a2 <- gt[, 2*i]      # allele 2
  
  ref <- na.omit(a1[a1 != "0"])[1]  # choose first observed allele as reference
  
  dosage[, i] <- (a1 != ref) + (a2 != ref)  # count non-ref alleles
  dosage[a1 == "0" | a2 == "0", i] <- NA    # set missing genotypes to NA
}

library(adegenet)

# build genlight object from dosage matrix
gl <- new("genlight", dosage)
ploidy(gl) <- 2  # diploid

# assign individual IDs and populations
indNames(gl) <- geno$Puma_ID
pop(gl) <- geno$Datset

# assign simple locus names
locNames(gl) <- paste0("L", seq_len(ncol(dosage)))

library(dartR)

# add required dartR metadata structure
gl <- gl.compliance.check(gl)

# remove monomorphic loci
gl <- gl.filter.monomorphs(gl)

# remove rare alleles below MAF threshold
gl <- gl.filter.maf(gl, threshold = 0.05)

# estimate LD-based effective population size (Ne)
Ne_out <- gl.LDNe(gl, neest.path = "/Users/georgezaragoza/Library/CloudStorage/OneDrive-Personal/UCF/Projects/Puma-AZ/Github/PumaBarriers/software/NeEstimator")

